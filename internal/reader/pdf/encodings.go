// baseEncoding returns the text of each code for a named base encoding.
func baseEncoding(n name) (t [256]string, ok bool) {
	switch n {
	case "StandardEncoding":
		for c, g := range standardNames {
			t[c] = glyphText(g)
		}
	case "WinAnsiEncoding":
		for c := 0x20; c < 256; c++ {
			switch {
			case c >= 0x80 && c < 0xA0:
				t[c] = string(winAnsiHigh[c-0x80])
			case c == 0x7F:
				t[c] = "•"
			default:
				t[c] = string(rune(c))
			}
		}
	case "MacRomanEncoding":
		for c := 0x20; c < 256; c++ {
			t[c] = string(charmap.Macintosh.DecodeByte(byte(c)))
		}
	case "PDFDocEncoding":
		for c := 0; c < 256; c++ {
			t[c] = string(pdfDocRune(byte(c)))
		}
	default:
		return t, false
	}
	return t, true
}

func pdfDocRune(c byte) rune {
	if r, ok := pdfDocLow[c]; ok {
		return r
	}
	if c >= 0x80 && c <= 0xA0 {
		return pdfDocHigh[c-0x80]
	}
	return rune(c)
}

// textString decodes a PDF text string (UTF-16BE or UTF-8 with BOM, else
// the PDF document encoding).
func textString(s pdfString) string {
	b := []byte(s)
	switch {
	case len(b) >= 2 && b[0] == 0xFE && b[1] == 0xFF:
		return utf16BE(b[2:])
	case len(b) >= 2 && b[0] == 0xFF && b[1] == 0xFE:
		u := make([]uint16, 0, len(b)/2)
		for i := 2; i+1 < len(b); i += 2 {
			u = append(u, uint16(b[i])|uint16(b[i+1])<<8)
		}
		return string(utf16.Decode(u))
	case len(b) >= 3 && b[0] == 0xEF && b[1] == 0xBB && b[2] == 0xBF:
		return strings.ToValidUTF8(string(b[3:]), "�")
	}
	var sb strings.Builder
	for _, c := range b {
		sb.WriteRune(pdfDocRune(c))
	}
	return sb.String()
}

func utf16BE(b []byte) string {
	u := make([]uint16, 0, len(b)/2)
	for i := 0; i+1 < len(b); i += 2 {
		u = append(u, uint16(b[i])<<8|uint16(b[i+1]))
	}
	return string(utf16.Decode(u))
}
