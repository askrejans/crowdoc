package fonts

import "strings"

// googleFontsCommit pins every google/fonts download to one tree so the
// catalog is reproducible; bump it together with the hashes.
const googleFontsCommit = "2eb0b48d5f760f62e286216f0859a8c540dbc1bd"

const ofl = "OFL-1.1"

// Catalog returns the curated families. The result is a copy and may be
// modified by the caller.
func Catalog() []Family {
	out := make([]Family, len(catalog))
	for i, f := range catalog {
		f.Scripts = append([]string(nil), f.Scripts...)
		f.Files = append([]File(nil), f.Files...)
		out[i] = f
	}
	return out
}

// lookupFamily finds a catalog family by name, case-insensitively.
func lookupFamily(name string) (Family, bool) {
	for _, f := range catalog {
		if strings.EqualFold(f.Name, name) {
			return f, true
		}
	}
	return Family{}, false
}

var urlEscaper = strings.NewReplacer("[", "%5B", "]", "%5D")

// googleFonts fills in the pinned raw URLs of files in a google/fonts
// directory such as "ofl/inter".
func googleFonts(dir string, files ...File) []File {
	base := "https://raw.githubusercontent.com/google/fonts/" + googleFontsCommit + "/" + dir + "/"
	for i := range files {
		files[i].URL = base + urlEscaper.Replace(files[i].Name)
	}
	return files
}

// libertinus takes files from the official Libertinus release archive: the
// google/fonts conversions of Libertinus Sans and Math lack their GSUB and
// MATH tables, which leaves no ligatures, small caps or math layout.
func libertinus(files ...File) []File {
	for i := range files {
		files[i].URL = "https://github.com/alerque/libertinus/releases/download/v7.051/Libertinus-7.051.zip"
		files[i].Member = "Libertinus-7.051/static/OTF/" + files[i].Name
		files[i].ArchiveSize = 9400628
		files[i].ArchiveSHA256 = "4d9be29b5cb380c35af8ba967abcc752ad1e07be1f738a9789c33e0dd7478c92"
	}
	return files
}

func file(name string, size int64, sha256 string) File {
	return File{Name: name, Size: size, SHA256: sha256}
}

