//go:embed assets/crowdoc.typ styles/*.typ
var files embed.FS

// FontSet holds resolved font fallback chains per role.
type FontSet struct {
	Main, Sans, Mono, Math, Heading []string
}

// Options configures rendering.
type Options struct {
	Style *Style
	// TemplateSource replaces the style's Typst source (a custom template
	// defining `template(meta, body)`).
	TemplateSource string
	Lang, Region   string
	Terms          map[string]string
	// Labels gives the text before and after the number in numbered
	// labels per kind (figure, table, listing, chapter, section, appendix).
	Labels    map[string][2]string
	PageOfFmt string // "Page %d of %d"
	Fonts     FontSet
	Unsafe    bool
	Hooks     Hooks
	Generator string
	// Now is used for the generated date when the document has none.
	Now time.Time
	// LocalDate formats a parsed date in the document language.
	LocalDate func(t time.Time) string
}

// Bundle is a self-contained Typst project.
type Bundle struct {
	// Files maps bundle-relative paths to contents (main.typ, crowdoc.typ,
	// style.typ). Image assets are added by the caller.
	Files    map[string][]byte
	Warnings []string
	// Settings are the resolved layout decisions (useful for callers).
	Settings Settings
}

// Settings records resolved layout decisions.
type Settings struct {
	TOC, NumberSections, TitlePage, Signatures bool
	// ShowTitle prints the title block. A title derived from the file name
	// is only printed on a title page unless the document asks for it.
	ShowTitle bool
}

// Render converts doc into a Typst bundle.
func Render(doc *ast.Document, o Options) (*Bundle, error) {
	if o.Style == nil {
		return nil, fmt.Errorf("no style selected")
	}
	styleSrc := o.TemplateSource
	if styleSrc == "" {
		data, err := files.ReadFile("styles/" + o.Style.File)
		if err != nil {
			return nil, fmt.Errorf("style %q: %w", o.Style.Name, err)
		}
		styleSrc = string(data)
	}
	lib, err := files.ReadFile("assets/crowdoc.typ")
	if err != nil {
		return nil, err
	}

	w := &writer{hooks: o.Hooks, labels: collectLabels(doc), unsafe: o.Unsafe}
	w.linksNote = o.Style.LinksAsNotes
	if doc.Meta.LinksAsNotes != nil {
		w.linksNote = *doc.Meta.LinksAsNotes
	}

	settings := resolveSettings(doc, o.Style)
	body := w.blocks(doc.Blocks)
	if !w.bibDone {
		if bib := w.bibliography(); bib != "" {
			body += "\n\n" + bib
		}
	}
	meta := w.metaDict(doc, o, settings)

	var main strings.Builder
	gen := o.Generator
	if gen == "" {
		gen = "crowdoc"
	}
	fmt.Fprintf(&main, "// Generated by %s. Edit the source document instead.\n", gen)
	main.WriteString("#import \"crowdoc.typ\": *\n#import \"style.typ\": template\n")
	main.WriteString("#show: template.with(")
	main.WriteString(meta)
	main.WriteString(")\n\n")
	main.WriteString(body)
	main.WriteString("\n")

	return &Bundle{
		Files: map[string][]byte{
			"main.typ":    []byte(main.String()),
			"crowdoc.typ": lib,
			"style.typ":   []byte(styleSrc),
		},
		Warnings: w.warnings,
		Settings: settings,
	}, nil
}

func collectLabels(doc *ast.Document) map[string]bool {
	labels := map[string]bool{}
	ast.WalkBlocks(doc.Blocks, func(b ast.Block) bool {
		switch n := b.(type) {
		case *ast.Heading:
			labels[n.Attr.ID] = true
		case *ast.Figure:
			if n.Caption != nil || n.Attr.ID != "" {
				labels[n.Attr.ID] = true
			}
		case *ast.Table:
			labels[n.Attr.ID] = true
		case *ast.MathBlock:
			labels[n.Label] = true
		case *ast.CodeBlock:
			labels[n.Attr.ID] = true
		case *ast.Div:
			if calloutKinds[firstClass(n.Attr)] {
				labels[n.Attr.ID] = true
			}
		case *ast.ReferenceList:
			for _, e := range n.Entries {
				labels[e.ID] = true
			}
		}
		return true
	})
	ast.WalkInlines(doc.Blocks, func(in ast.Inline) {
		if sp, ok := in.(*ast.Span); ok && sp.Attr.ID != "" {
			labels[sp.Attr.ID] = true
		}
	})
	delete(labels, "")
	return labels
}

func firstClass(a ast.Attr) string {
	if len(a.Classes) == 0 {
		return ""
	}
	return a.Classes[0]
}

func resolveSettings(doc *ast.Document, st *Style) Settings {
	s := Settings{NumberSections: st.NumberSections, TitlePage: st.TitlePage && !doc.Meta.NoTitlePage}
	if doc.Meta.NumberSections != nil {
		s.NumberSections = *doc.Meta.NumberSections
	}
	if doc.Meta.ShowTitle != nil {
		s.ShowTitle = *doc.Meta.ShowTitle
	} else {
		s.ShowTitle = !doc.Meta.TitleFromName || s.TitlePage
	}
	switch {
	case doc.Meta.TOC != nil:
		s.TOC = *doc.Meta.TOC
	case st.TOC == "always":
		// Even "always" needs something to list: a document without
		// headings (a scanned page, a short note) gets no empty contents.
		ast.WalkBlocks(doc.Blocks, func(b ast.Block) bool {
			if _, ok := b.(*ast.Heading); ok {
				s.TOC = true
			}
			return !s.TOC
		})
	case st.TOC == "auto":
		// A contents page only pays off in a longer document.
		top, words := 0, 0
		for _, b := range doc.Blocks {
			if h, ok := b.(*ast.Heading); ok && h.Level == 1 {
				top++
			}
		}
		ast.WalkBlocks(doc.Blocks, func(b ast.Block) bool {
			if p, ok := b.(*ast.Para); ok {
				words += len(strings.Fields(ast.PlainText(p.Inlines)))
			}
			return true
		})
		s.TOC = (top >= 4 && words >= 1200) || top >= 8
	}
	switch {
	case doc.Meta.Signatures != nil:
		s.Signatures = *doc.Meta.Signatures
	case st.Signatures == "always":
		s.Signatures = true
	case st.Signatures == "auto":
		s.Signatures = looksLikeAgreement(doc.Meta.Title + " " + doc.Meta.DocType)
	}
	return s
}

var agreementRe = regexp.MustCompile(`(?i)agreement|contract|\bnda\b|līgums|ligums|vienošanās|vertrag|contrat|contrato|contratto|umowa|smlouva|sutartis|leping|sopimus|avtal|aftale|overeenkomst|szerződés|sözleşme|договор|угода`)

func looksLikeAgreement(s string) bool { return agreementRe.MatchString(s) }

