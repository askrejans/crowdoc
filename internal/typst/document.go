type dict struct{ parts []string }

func (d *dict) add(k, v string) {
	if !strings.HasPrefix(k, "\"") {
		k = strings.TrimSpace(k)
	}
	d.parts = append(d.parts, k+": "+v)
}

func (d *dict) String() string {
	if len(d.parts) == 0 {
		return "(:)"
	}
	return "(\n  " + strings.Join(d.parts, ",\n  ") + ",\n)"
}

func array(items []string) string {
	switch len(items) {
	case 0:
		return "()"
	case 1:
		return "(" + items[0] + ",)"
	}
	return "(" + strings.Join(items, ", ") + ")"
}
